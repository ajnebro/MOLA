"""Phase 2b inputs: tuning bounds from the phase 2 reference fronts, and irace's parameter files.

- data/tuning_bounds.json: per pilot problem, the ideal and nadir of the union of every phase 2
  final front on that problem (phase2/data/reference_fronts.npz). Arms A and B normalize the
  tuning objective with them instead of the default-NSGA-II calibration of phase 2.
- irace/parameters.txt and irace/default.txt: VAMOS's invariant NSGA-II space
  (`runs.invariant_nsgaii_space()`) in irace syntax, generated so that it cannot drift from the
  space F-Race uses; default.txt holds NSGA-II's textbook default (`tune_pilot.BASELINE`).

Run locally from the repository root:  python research/phase2b/scripts/make_inputs.py
"""

import json
import re
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "phase2" / "scripts"))

from common import DATA as PHASE2_DATA  # noqa: E402
from common import pilot_problems  # noqa: E402
from runs import invariant_nsgaii_space  # noqa: E402
from tune_pilot import BASELINE  # noqa: E402

PHASE2B = HERE.parent
_CONDITION = re.compile(r"cfg\['(\w+)'\] == '([^']+)'")


def _irace_condition(expr: str) -> str:
    """Translate a VAMOS condition (one parent, ==, joined by `or`) into irace syntax."""
    pairs = _CONDITION.findall(expr)
    parents = {parent for parent, _ in pairs}
    if len(parents) != 1:
        raise ValueError(f"unsupported condition: {expr}")
    parent = parents.pop()
    values = [value for _, value in pairs]
    if len(values) == 1:
        return f'{parent} == "{values[0]}"'
    quoted = ", ".join(f'"{value}"' for value in values)
    return f"{parent} %in% c({quoted})"


def _irace_value(value) -> str:
    return "NA" if value is None else str(value)


def write_irace_files(directory: Path) -> None:
    space = invariant_nsgaii_space()
    condition_of = {c.param_name: _irace_condition(c.expr) for c in space.conditions}
    lines = ["# Generated by research/phase2b/scripts/make_inputs.py from runs.invariant_nsgaii_space().",
             "# name  switch  type  values  [| condition]"]
    for name, spec in space.params.items():
        kind = type(spec).__name__
        if kind == "Int":
            line = f'{name} "--{name} " {"i,log" if spec.log else "i"} ({spec.low}, {spec.high})'
        elif kind == "Real":
            line = f'{name} "--{name} " {"r,log" if spec.log else "r"} ({spec.low}, {spec.high})'
        elif kind == "Categorical":
            choices = ", ".join(f'"{choice}"' for choice in spec.choices)
            line = f'{name} "--{name} " c ({choices})'
        else:
            raise ValueError(f"unsupported parameter type {kind} for {name}")
        if name in condition_of:
            line += f" | {condition_of[name]}"
        lines.append(line)
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "parameters.txt").write_text("\n".join(lines) + "\n")

    names = list(space.params)
    default = {name: (BASELINE[name] if name in BASELINE and space.is_active(name, BASELINE) else None)
               for name in names}
    (directory / "default.txt").write_text(
        " ".join(names) + "\n" + " ".join(_irace_value(default[n]) for n in names) + "\n")


def write_tuning_bounds() -> None:
    fronts = np.load(PHASE2_DATA / "reference_fronts.npz")
    bounds = {p: {"ideal": fronts[p].min(axis=0).tolist(), "nadir": fronts[p].max(axis=0).tolist()}
              for p in pilot_problems()}
    (PHASE2B / "data").mkdir(parents=True, exist_ok=True)
    (PHASE2B / "data" / "tuning_bounds.json").write_text(json.dumps(bounds, indent=2) + "\n")


if __name__ == "__main__":
    write_tuning_bounds()
    write_irace_files(PHASE2B / "irace")
    print((PHASE2B / "irace" / "parameters.txt").read_text())
    print((PHASE2B / "irace" / "default.txt").read_text())
